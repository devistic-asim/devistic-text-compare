import type { DiffModel, DiffOptions, DiffViewMode, Span } from './types.ts';
import { describeStats } from './types.ts';

export function escapeHtml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function renderSpans(spans: Span[]): string {
  if (spans.length === 0) return '&nbsp;';
  const partial = spans.some((span) => span.kind === 'equal') && spans.some((span) => span.kind !== 'equal');
  return spans
    .map((span) => {
      const text = span.text.length > 0 ? escapeHtml(span.text) : '&nbsp;';
      if (!partial || span.kind === 'equal') return text;
      return `<mark class="${span.kind}">${text}</mark>`;
    })
    .join('');
}

function optionSummary(options: DiffOptions): string {
  const flags = [
    options.ignoreWhitespace ? 'whitespace ignored' : '',
    options.ignoreCase ? 'case ignored' : '',
    options.ignoreBlankLines ? 'blank lines ignored' : '',
    `${options.granularity} highlighting`,
  ].filter(Boolean);
  return flags.join(' · ');
}

export function renderHtmlExport(input: {
  originalName: string;
  changedName: string;
  model: DiffModel;
  view: DiffViewMode;
  options: DiffOptions;
}): string {
  const title = `Diff: ${input.originalName} → ${input.changedName}`;
  const rows = input.model.rows
    .map((row) => {
      if (input.view === 'unified') {
        if (row.kind === 'change') {
          return `<tr class="del"><td class="n">${row.oldNumber ?? ''}</td><td class="n"></td><td class="m">−</td><td class="code">${renderSpans(row.left)}</td></tr>
<tr class="ins"><td class="n"></td><td class="n">${row.newNumber ?? ''}</td><td class="m">+</td><td class="code">${renderSpans(row.right)}</td></tr>`;
        }
        const marker = row.kind === 'delete' ? '−' : row.kind === 'insert' ? '+' : ' ';
        const klass = row.kind === 'equal' ? 'eq' : row.kind === 'delete' ? 'del' : 'ins';
        const spans = row.kind === 'insert' ? row.right : row.left;
        return `<tr class="${klass}"><td class="n">${row.oldNumber ?? ''}</td><td class="n">${row.newNumber ?? ''}</td><td class="m">${marker}</td><td class="code">${renderSpans(spans)}</td></tr>`;
      }
      const klass = row.isChange ? row.kind : 'eq';
      return `<tr class="${klass}"><td class="n">${row.oldNumber ?? ''}</td><td class="code">${renderSpans(row.left)}</td><td class="n">${row.newNumber ?? ''}</td><td class="code">${renderSpans(row.right)}</td></tr>`;
    })
    .join('\n');

  const head =
    input.view === 'unified'
      ? '<tr><th>Old</th><th>New</th><th></th><th>Text</th></tr>'
      : `<tr><th colspan="2">${escapeHtml(input.originalName)}</th><th colspan="2">${escapeHtml(input.changedName)}</th></tr>`;

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<style>
  :root { color-scheme: light; }
  body { margin: 0; font-family: "Segoe UI", system-ui, sans-serif; background: #F5F9FC; color: #1E293B; }
  header { padding: 24px 28px 8px; }
  h1 { font-size: 1.25rem; margin: 0 0 8px; }
  p { margin: 0 0 6px; color: #637285; }
  table { width: 100%; border-collapse: collapse; background: #fff; font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace; font-size: 13px; }
  th, td { text-align: left; vertical-align: top; padding: 2px 8px; }
  th { font-family: "Segoe UI", system-ui, sans-serif; font-size: 12px; color: #637285; background: #F5F9FC; position: sticky; top: 0; }
  td.n { color: #637285; text-align: right; width: 3rem; user-select: none; }
  td.m { width: 1.25rem; color: #637285; }
  td.code { white-space: pre-wrap; overflow-wrap: anywhere; }
  tr.del td.code, tr.del td.m { background: #FDECEC; }
  tr.ins td.code, tr.ins td.m { background: #E5F7EF; }
  tr.change td.code { background: #FFF6C2; }
  mark.delete { background: #F6C1C1; color: #7F1D1D; }
  mark.insert { background: #B7E8D2; color: #145C3E; }
  footer { padding: 16px 28px 28px; color: #637285; font-size: 0.85rem; }
</style>
</head>
<body>
<header>
  <h1>Devistic Text Compare</h1>
  <p>Exported on this device. Nothing was uploaded.</p>
  <p>${escapeHtml(input.originalName)} → ${escapeHtml(input.changedName)}</p>
  <p>${escapeHtml(describeStats(input.model.stats))}. ${escapeHtml(optionSummary(input.options))}.</p>
</header>
<main>
<table>
<thead>${head}</thead>
<tbody>
${rows}
</tbody>
</table>
</main>
<footer>Generated by Devistic Text Compare. https://github.com/devistic-asim/devistic-text-compare</footer>
</body>
</html>
`;
}
